import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {inspectAtlas,sha256} from './pixel-atlas-inspection.mjs';
const dir=new URL('../assets/battle-pixel/animations/',import.meta.url);
const provenance=JSON.parse(fs.readFileSync(new URL('mission-provenance.json',dir),'utf8'));
const assets=provenance.assets.map(source=>{
  const bytes=fs.readFileSync(new URL(source.file,dir)),cols=source.grid.cols,rows=source.grid.rows;
  return {file:source.file,cols,rows,frames:cols*rows,bytes:bytes.length,sha256:sha256(bytes),...inspectAtlas(bytes,cols,rows)};
});
const path=new URL('mission-manifest.json',dir);
if(process.argv.includes('--write-manifest'))fs.writeFileSync(path,JSON.stringify({schemaVersion:1,assets:assets.map(({frameDetails,...asset})=>asset)},null,2)+'\n');
const manifest=JSON.parse(fs.readFileSync(path,'utf8'));
test('mission machine and teacher punch assets preserve the generated bytes and prompts',()=>{
  assert.equal(assets.length,3);assert.equal(assets.reduce((sum,a)=>sum+a.frames,0),20);
  assert.deepEqual(manifest.assets,assets.map(({frameDetails,...asset})=>asset));
  assert.ok(provenance.assets.every(a=>a.prompt.length>100&&/pixel/i.test(a.prompt)));
});
for(const asset of assets)test(asset.file+' contains distinct padded transparent frames',()=>{
  const total=asset.width*asset.height;
  assert.ok(asset.alpha.transparentPixels>total*.15);assert.ok(asset.alpha.nearOpaquePixels>total*.005);
  assert.ok(Math.abs(asset.width/asset.cols-asset.height/asset.rows)<=1);
  assert.equal(new Set(asset.frameDetails.map(f=>f.fingerprint)).size,asset.frames);
  for(const frame of asset.frameDetails){assert.equal(frame.edgePixels,0);assert.ok(frame.occupiedPixels>frame.area*.005&&frame.occupiedPixels<frame.area*.85);assert.ok(frame.coloredPixels>100);}
});
